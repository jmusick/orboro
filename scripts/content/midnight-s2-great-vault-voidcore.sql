## The Knockout List Changes the Math

The real value of a Voidcore is not simply that it produces another random item. Bonus rolls use a knockout system.

When a Voidcore awards an item, that item is recorded for your character and removed from subsequent bonus rolls from that loot pool. Each roll therefore improves the odds of the next one. Blizzard described this intended behavior when it explained and fixed the initial Season 1 duplicate bug: [each Voidcore item is checked off a character-specific list](https://us.forums.blizzard.com/en/wow/t/bonus-rolls-%E2%80%93-what-happened-and-next-steps/2296587/1).

There is one important limitation: **taking an item directly from the Great Vault does not check it off the bonus-roll list.** Neither does receiving it as an ordinary drop. If you later spend a Voidcore on the same pool, the system can award that item again.

That is why an exciting Vault item can still be the less efficient choice.

Imagine that a boss has four items available to your loot specialization and you want all four.

- Taking four consecutive Voidcores and rolling that boss four times gives you all four items. Each roll removes one option.
- Taking one of those items from the Vault and then using three Voidcores still leaves all four items in the bonus-roll pool.

In the second scenario, there is a 75% chance that one of those three rolls reproduces the item you already selected from the Vault. After four weekly selections, you expect to own 3.25 unique items instead of the four guaranteed by choosing four Voidcores.

The guaranteed Vault item feels safer in the moment, but the Voidcore makes the entire sequence more deterministic.

